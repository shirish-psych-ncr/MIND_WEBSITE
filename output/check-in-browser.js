async (page) => {
  const assert = (ok, message) => { if (!ok) throw new Error(message); };
  const url = 'http://127.0.0.1:4329/aasha/developmental-check-in';
  await page.goto(url);
  await page.evaluate(() => localStorage.removeItem('aasha-check-in-v1'));
  await page.reload();
  const start = async (years = '3') => {
    await page.getByRole('textbox', {name:'Nickname (optional)'}).fill('Test child');
    await page.getByRole('spinbutton', {name:'Age: years'}).fill(years);
    await page.getByRole('button', {name:'Begin check-in',exact:true}).click();
  };
  const answer = async (name) => { await page.getByRole('radio',{name,exact:true}).check(); await page.getByRole('button',{name:'Continue',exact:true}).click(); };
  const complete = async () => {
    for (let i=0;i<30 && await page.locator('#check-question').isVisible();i++) await answer('No');
    await page.getByRole('button',{name:'Create my summary'}).click();
  };
  await start();
  await answer('No'); await answer('Not sure');
  assert((await page.locator('#check-prompt').innerText()).includes('everyday play'), 'Follow-up not inserted');
  await answer('Yes');
  await page.getByRole('button',{name:'Back',exact:true}).click();
  await page.getByRole('button',{name:'Back',exact:true}).click();
  await answer('No');
  assert((await page.locator('#check-prompt').innerText()).includes('communicates their needs'), 'Obsolete follow-up remains');
  await complete();
  assert((await page.locator('#result-next').innerText()).includes('does not rule out'), 'Incorrect all-no result');
  assert(!(await page.locator('#result-list').innerText()).includes('everyday play'), 'Stale answer in result');
  assert(await page.locator('#check-share').isDisabled(), 'Sharing not opt-in');
  await page.locator('#check-message').fill('Only this edited draft');
  await page.locator('#share-consent').check();
  await page.evaluate(() => { window.__opened = null; window.open = (...args) => { window.__opened = args; return null; }; });
  await page.locator('#check-share').click();
  const opened = await page.evaluate(() => window.__opened);
  assert(new URL(opened[0]).searchParams.get('text') === 'Only this edited draft', 'Draft edits not respected');
  assert(opened[2] === 'noopener,noreferrer', 'Unsafe opener');
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile overflow');
  await page.screenshot({path:'output/aasha-check-in-mobile.png',fullPage:true});
  await page.addScriptTag({path:'node_modules/axe-core/axe.min.js'});
  const audit = await page.evaluate(async () => (await window.axe.run(document.querySelector('#check-in'))).violations.map(v => ({id:v.id,impact:v.impact,description:v.description})));
  assert(!audit.length, JSON.stringify(audit));
  await page.emulateMedia({media:'print'});
  assert(!(await page.locator('#check-share').isVisible()), 'Share UI appears in print');
  assert(await page.locator('#result-next').isVisible(), 'Print summary missing');
  await page.pdf({path:'output/aasha-check-in-summary.pdf',format:'A4'});
  await page.emulateMedia({media:'screen'});
  await page.locator('#check-save').check();
  await page.reload();
  assert(await page.locator('[name=nickname]').inputValue() === 'Test child', 'Saved child not restored');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#check-reset').click();
  assert(await page.locator('[name=nickname]').inputValue() === '', 'Reset retains child');
  assert(await page.evaluate(() => localStorage.getItem('aasha-check-in-v1')) === null, 'Reset retains saved state');
  assert(await page.locator('#check-message').inputValue() === '', 'Reset retains draft');
  await start('0'); await answer('Yes');
  assert(await page.locator('#loss-note').isVisible(), 'Loss guidance not immediate');
  await complete();
  assert((await page.locator('#result-next').innerText()).includes('promptly'), 'Loss guidance missing');
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(() => document.documentElement.dataset.theme = 'dark');
  await page.screenshot({path:'output/aasha-check-in-desktop-dark.png',fullPage:true});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Desktop overflow');
  await page.evaluate(() => localStorage.setItem('aasha-check-in-v1','{broken'));
  await page.reload();
  assert((await page.locator('#check-status').innerText()).includes('could not be restored'), 'Corrupt data not handled');
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error('Storage blocked'); }; });
  await page.reload(); await start(); await page.locator('#check-save').check();
  assert((await page.locator('#check-status').innerText()).includes('unavailable'), 'Storage failure not explained');
  await complete();
  await page.evaluate(() => document.documentElement.dataset.theme = 'light');
  await page.screenshot({path:'output/aasha-check-in-desktop.png',fullPage:true});
  return 'PASS: branching, pruning, results, explicit edited sharing, mobile/desktop overflow, axe, print, save/restore, reset, loss guidance, corrupted and blocked storage';
}
